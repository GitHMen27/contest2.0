function normalize(value: string): string {
  return value.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim();
}

/**
 * Детерминированный демо-поиск вместо сетевого вызова.
 * В production этот слой заменяется на POST /rag/ask.
 */
export function findDemoAnswer(query: string): DemoAnswer {
  const normalized = normalize(query);
  if (!normalized) return FALLBACK;

  let best: DemoAnswer | null = null;
  let bestScore = 0;

  for (const answer of DEMO_ANSWERS) {
    let score = 0;
    for (const keyword of answer.keywords) {
      if (normalized.includes(normalize(keyword))) {
        score += keyword.length > 4 ? 2 : 1;
      }
    }
    if (score > bestScore) {
      best = answer;
      bestScore = score;
    }
  }

  return best ?? FALLBACK;
}
